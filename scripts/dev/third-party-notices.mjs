// Regenerates THIRD_PARTY_NOTICES.md from the installed production dependencies: every
// package electron-builder packs, with its licence and the licence text it ships.
// Run after `npm ci`: node scripts/dev/third-party-notices.mjs
// Uses license-checker-rseidelsohn through npx; the hand-written section covers what npm
// metadata can't see (Electron and Chromium, the libraries inside native addons).

import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(fileURLToPath(new URL('../..', import.meta.url)))
const json = execFileSync(
  'npx',
  ['--yes', 'license-checker-rseidelsohn@4', '--production', '--excludePrivatePackages', '--json'],
  { cwd: root, encoding: 'utf8', shell: process.platform === 'win32', maxBuffer: 64 * 1024 * 1024 }
)
const packages = Object.entries(JSON.parse(json)).sort(([a], [b]) => a.localeCompare(b))

const electronVersion = JSON.parse(readFileSync(resolve(root, 'node_modules/electron/package.json'), 'utf8')).version

// Licence choices and source notices the licence texts alone don't state, by package name.
const NOTES = {
  jszip: 'Notula uses JSZip under the MIT licence.',
  'ical.js': 'ical.js is used unmodified under the Mozilla Public License 2.0. Its source code is available at https://github.com/kewisch/ical.js.'
}

const out = []
out.push('# Third-party notices', '')
out.push(
  'Notula is licensed under the Apache License 2.0 (see `LICENSE`). The Notula installer also ships the',
  'third-party software listed below, each under its own licence. This file is generated by',
  '`scripts/dev/third-party-notices.mjs` from the production dependencies in `package-lock.json`.',
  ''
)
out.push('## Bundled outside npm metadata', '')
out.push(
  `- **Electron ${electronVersion}** (MIT) and **Chromium**, **Node.js** and the other components Electron includes.`,
  '  Their licences ship with every installed copy as `LICENSE` and `LICENSES.chromium.html` next to `Notula.exe`.',
  '- **ONNX Runtime** (MIT, Copyright (c) Microsoft Corporation), inside `sherpa-onnx-win-x64` as `onnxruntime.dll`.',
  '- **sherpa-onnx** (Apache-2.0, the k2-fsa project), inside',
  '  `sherpa-onnx-node` and `sherpa-onnx-win-x64`.',
  '- **SQLite** (public domain) and **SQLite3 Multiple Ciphers** (MIT, Copyright (c) Ulrich Telle), compiled into',
  '  `better-sqlite3-multiple-ciphers`.',
  '',
  'Speech models are not part of the installer; Notula downloads them on request. See `MODELS.md`.',
  ''
)
out.push('## npm packages', '')
out.push('| Package | Version | Licence | Repository |', '|---|---|---|---|')
for (const [id, p] of packages) {
  const at = id.lastIndexOf('@')
  out.push(`| ${id.slice(0, at)} | ${id.slice(at + 1)} | ${[].concat(p.licenses).join(', ')} | ${p.repository ?? ''} |`)
}
out.push('', `${packages.length} packages.`, '')
out.push('## Licence texts', '')
for (const [id, p] of packages) {
  out.push(`### ${id}`, '')
  const note = NOTES[id.slice(0, id.lastIndexOf('@'))]
  if (note) out.push(note, '')
  const file = p.licenseFile && existsSync(p.licenseFile) && !/readme/i.test(p.licenseFile) ? p.licenseFile : null
  if (file) {
    const text = readFileSync(file, 'utf8').replace(/\r\n/g, '\n').trim()
    out.push('```text', text.replace(/```/g, "'''"), '```', '')
  } else {
    out.push(`Licensed under ${[].concat(p.licenses).join(', ')}; the package ships no separate licence file.`, '')
  }
}
writeFileSync(resolve(root, 'THIRD_PARTY_NOTICES.md'), out.join('\n'))
console.log(`THIRD_PARTY_NOTICES.md: ${packages.length} packages`)
