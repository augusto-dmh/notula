// Lesson notes when a lesson ends: for a finished lesson of a course whose `on_end` is `notes`,
// with no lesson notes yet and at least 150 words watched, generate once with the Lesson template
// from the watched part. Driven by bus `sources:lesson-finished`.
//
// - Generation goes through the existing end-of-meeting path (`ctx.enhance.autoGenerate`) with
//   the user's notes model and the Lesson template as the note's template; the prompt inputs use
//   the watched scope (plan.ts). Its failure leaves Generate notes with the error, and nothing
//   retries.
// - Local-only mode allows a local model only; otherwise nothing is generated and a notice says
//   why. A scoped transcript over the model's budget isn't generated by itself either: the
//   interface warns with the cut point (`lessonNotesPreflight`) and the user decides.
// - A rewatch never regenerates: a note that has or had lesson notes (any summary panel, a deleted
//   one too, so this holds across restarts) is skipped, and each note is tried once per run, claimed
//   before anything is awaited so two close finishes can't both pass.
// - *Lesson notes ready* · **Open** when the note isn't on screen.
// Logs: states, counts and reasons only.

import type { PushChannel } from '@shared/ipc'
import { LESSON_TEMPLATE_ID } from '@shared/types/sources'
import { SUGGESTED_ACTIONS_SLUG } from '@shared/types/enhance'
import type { MainContext } from '../context'
import { budgetCut, formatTranscript, type WatchedScope } from '../enhance/transcript'
import { transcriptBudget } from '../enhance/note-context'
import { showMainWindow } from '../lifecycle'
import { currentProvider } from '../llm/registry'
import { log } from '../log'
import { egressBlocked } from '../privacy'
import { setNoteTemplate } from '../templates/pending'
import { lessonScope } from './plan'

/** Fewer watched words than this: no lesson notes. */
export const LESSON_NOTES_MIN_WORDS = 150

/** Notes tried this run: a rewatch, or a second finish, never generates again. */
const tried = new Set<string>()
/** Panels started here, for the ready card. */
const started = new Map<string, string>()
let listening = false

export type LessonNotesSkip = 'not-course' | 'button' | 'has-notes' | 'tried' | 'too-short' | 'local-only' | 'no-model' | 'over-budget' | 'not-started'

/** What lesson notes would use now: the scope, its word count, and the budget cut (null = fits). */
export async function lessonNotesPreflight(
  ctx: MainContext,
  noteId: string
): Promise<{ scope: WatchedScope; words: number; cut: { cutAtMs: number | null; usedChars: number } | null } | null> {
  const scoped = await lessonScope(ctx, noteId)
  if (!scoped) return null
  const text = formatTranscript(scoped.chunks, { media: true }).text
  const words = text.split(/\s+/).filter((w) => w && !/^\[[\d:]+\]$/.test(w)).length
  const provider = await currentProvider(ctx.settings, ctx.secrets)
  const budget = await transcriptBudget(provider)
  return { scope: scoped.scope, words, cut: budgetCut(text, budget) }
}

/** Has or had lesson notes: a deleted panel counts, so deleting them never brings them back by itself. */
async function hadLessonNotes(ctx: MainContext, noteId: string): Promise<boolean> {
  const panels = await ctx.storage.listPanels(noteId, { includeDeleted: true })
  return panels.some((p) => p.template_key !== SUGGESTED_ACTIONS_SLUG)
}

function notice(ctx: MainContext, noteId: string, body: string): void {
  ctx.notify.show({
    variant: 'info',
    title: 'Lesson notes weren’t written',
    body,
    infoActions: [{ id: 'open', label: 'Open note' }],
    showDelayMs: 0,
    hideAfterMs: 60_000,
    quietWhileRecording: false,
    allowDuringOnboarding: false,
    onAction: (a) => {
      if (a === 'info:open') openNote(noteId)
    }
  })
}

function openNote(noteId: string): void {
  const main = showMainWindow()
  main?.webContents.send('deeplink:received' satisfies PushChannel, { type: 'show-note', data: { documentId: noteId, openSource: 'notification' } })
}

function listen(ctx: MainContext): void {
  if (listening) return
  listening = true
  ctx.bus.on('enhance:completed', ({ noteId, panelId, ok }) => {
    if (started.get(noteId) !== panelId) return
    started.delete(noteId)
    log('info', 'sources:lesson-notes-done', { ok })
    // A failure stays on the panel with its error; nothing retries.
    if (!ok) return
    if (ctx.ui.viewingNoteId() === noteId && ctx.ui.mainWindowFocused()) return
    ctx.notify.show({
      variant: 'info',
      title: 'Lesson notes ready',
      body: '',
      infoActions: [{ id: 'open', label: 'Open' }],
      showDelayMs: 0,
      hideAfterMs: 60_000,
      quietWhileRecording: false,
      allowDuringOnboarding: false,
      onAction: (a) => {
        if (a === 'info:open') openNote(noteId)
      }
    })
  })
}

/** The lesson of `noteId` finished: its lesson notes, when they are due. */
export async function onLessonFinished(ctx: MainContext, noteId: string): Promise<void> {
  listen(ctx)
  const skip = (reason: LessonNotesSkip): void => log('info', 'sources:lesson-notes-skipped', { reason })
  if (tried.has(noteId)) return skip('tried')
  // Claimed now; released only when the lesson turns out not to qualify yet.
  tried.add(noteId)
  const release = (reason: LessonNotesSkip): void => {
    tried.delete(noteId)
    skip(reason)
  }
  const source = await ctx.storage.getNoteSource(noteId)
  const series = source?.series_id ? await ctx.storage.getSeries(source.series_id) : null
  if (!source || !series?.registered_at) return release('not-course')
  if (series.on_end !== 'notes') return release('button')
  if (await hadLessonNotes(ctx, noteId)) return skip('has-notes')
  // Local-only mode: a local model only, and nothing leaves the PC.
  if (await egressBlocked(ctx, { kind: 'llm' })) {
    notice(ctx, noteId, 'Local-only mode is on. Choose a local AI model in Settings, then generate notes in the note.')
    return skip('local-only')
  }
  const pre = await lessonNotesPreflight(ctx, noteId)
  if (!pre || pre.words < LESSON_NOTES_MIN_WORDS) return release('too-short')
  if (pre.cut) {
    notice(ctx, noteId, 'The part you watched is longer than your AI model can read at once. Open the note to choose what to use.')
    return skip('over-budget')
  }
  const provider = await currentProvider(ctx.settings, ctx.secrets)
  if (!(await provider.available()).ok) {
    notice(ctx, noteId, 'No AI model is set up. Add one in Settings, then generate notes in the note.')
    return skip('no-model')
  }
  setNoteTemplate(noteId, LESSON_TEMPLATE_ID)
  const r = await ctx.enhance.autoGenerate(noteId)
  if (!r) return skip('not-started')
  started.set(noteId, r.panelId)
  log('info', 'sources:lesson-notes-started', { words: pre.words, whole: pre.scope.whole, notes: pre.scope.noteCount })
}
